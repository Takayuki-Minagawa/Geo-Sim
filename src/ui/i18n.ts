export function sourceTypeLabel(sourceType: string, locale: Locale): string {
  if (locale === 'ja') {
    return sourceType === 'manual' ? '手入力' : sourceType
  }
  const labels: Record<string, string> = {
    manual: 'Manual input',
    'jiban-json': 'Jiban JSON',
    'legacy-xls': 'Legacy workbook',
    csv: 'CSV',
  }
  return labels[sourceType] ?? sourceType
}

export function classificationLabel(value: string, locale: Locale): string {
  return locale === 'en' ? classificationLabels[value] ?? value : value
}

export function applicabilityLabel(check: ApplicabilityCheck, locale: Locale): string {
  return applicabilityLabels[check.id]?.[locale] ?? check.label
}

export function applicabilityDetail(check: ApplicabilityCheck, locale: Locale): string {
  if (locale === 'ja') return check.detail
  if (/^[\d.]+\s*(m\/s|m|°)$/.test(check.detail)) return check.detail
  if (check.status === 'not-assessed') return copies.en.expertReviewAfterAnalysis
  return check.status === 'pass' ? 'Condition satisfied' : 'Condition not satisfied or input incomplete'
}

export function localizedMessage(message: AnalysisMessage, locale: Locale): string {
  if (locale === 'ja') return message.message
  return englishMessages[message.code] ?? `Review diagnostic ${message.code} and the related input or calculation setting.`
}
