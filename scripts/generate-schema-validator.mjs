import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schema = JSON.parse(
  await readFile(resolve(root, 'schemas/jiban-project.schema.json'), 'utf8'),
)
const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true } })
const validate = ajv.compile(schema)
const outputDirectory = resolve(root, 'src/generated')
const validatorCode = standaloneCode(ajv, validate).replace(
  /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/,
  'const $1 = (str) => { const len = str.length; let length = 0; let pos = 0; while (pos < len) { length += 1; let value = str.charCodeAt(pos); pos += 1; if (value >= 0xd800 && value <= 0xdbff && pos < len) { value = str.charCodeAt(pos); if ((value & 0xfc00) === 0xdc00) pos += 1; } } return length; };',
)

await mkdir(outputDirectory, { recursive: true })
await writeFile(
  resolve(outputDirectory, 'validateJibanProject.js'),
  `/* Generated by scripts/generate-schema-validator.mjs. Do not edit. */\n${validatorCode}`,
  'utf8',
)
